"""Абстракция скачивания страниц сайта.

Разделение ответственности (SRP):
- ``Fetch`` — отправляет HTTP-запросы, получает HTML-страницы и управляет
  перебором страниц пагинации. Собирает ссылки, делегируя разбор HTML
  абстракции ``Parser`` (DIP).
- ``Parser`` — разбирает HTML, который предоставил ``Fetch``.
"""

from abc import ABC, abstractmethod
from datetime import date


class Fetch(ABC):
    """Абстракция скачивания страниц и сбора ссылок с сайта.

    Конкретные реализации знают, как построить URL пагинации и скачать
    страницы. Разбор HTML они делегируют абстракции ``Parser``.
    """

    @abstractmethod
    async def parse(self) -> list[str]:
        """Сканирует страницы сайта и возвращает список ссылок."""
        ...

    def extract_date(self, url: str) -> date | None:
        """Извлекает дату из URL.

        Каждый сайт знает формат своих URL, поэтому конкретная реализация
        переопределяет этот метод для корректного извлечения даты.
        По умолчанию возвращает None (дата не извлекается).

        Args:
            url: URL для извлечения даты.

        Returns:
            Объект date или None, если дату не удалось извлечь.
        """
        return None
